# Функція, що повертає функцію
def outer():
    def inner():
        print("Hello from inner")
    return inner

f = outer()

f()

# Функція може бути значенням, тому що вона може присвоюватися змінним, може передаватися як аргумент, може повертатися з інших функцій.

# Це є прикладом функцій вищого порядку, тому що функція outer повертає функцію inner, отже вона є функцією вищого порядку.